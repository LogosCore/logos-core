// Refcounted, deduplicated GraphQL subscription registry.
//
// Multiple React components subscribing to the same (document, variables)
// pair share a single underlying graphql-ws subscription. The subscription
// is opened on the singleton WebSocket client when the first listener
// attaches and disposed when the last one detaches. All data events fan
// out to every listener.
//
// The graphql-ws client (lib/graphql-ws-client.ts) owns transport-level
// concerns (connect, reconnect, exponential backoff, refresh-on-close).
// This file owns subscription-level concerns: dedup, fanout, the refcount
// lifecycle, pausing while the tab is hidden, opening again one the server
// ended, and saying when events were lost.
//
// The React-facing wrapper is use-subscription.ts.

import type { Client } from "graphql-ws"
import type { TypedDocumentString } from "@/graphql/gql/graphql"
import { getGraphQLWSClient } from "@/lib/graphql-ws-client"

// Documents are query strings, not ASTs — codegen runs with
// `documentMode: "string"`. That removed the print() this file used to memoize
// around, and with it graphql-js from the bundle. The operation name is now read
// off the string instead of walking `definitions`; both remain cached per
// document, since the registry key is built on every subscribe.
type AnyDocument = TypedDocumentString<unknown, unknown>

type Listener<T> = (data: T) => void
// Receives a server-side refusal of the subscription (joined messages).
type ErrorListener = (message: string) => void

interface SharedSubscription<T> {
  key: string
  query: string
  operationName: string | undefined
  variables: unknown
  listeners: Set<Listener<T>>
  errorListeners: Set<ErrorListener>
  /** Disposes the open graphql-ws subscription; null while none is open. */
  dispose: (() => void) | null
  /**
   * The open one's token. graphql-ws completes a subscription disposed here
   * too, a moment later: its callbacks then find another token, or none,
   * and are ignored.
   */
  open: object | null
  /** When it was last opened, and how many times running the server ended it soon after. */
  openedAt: number
  ends: number
  /** Its reopen, waiting after the server ended it. */
  retry: ReturnType<typeof setTimeout> | null
}

/**
 * The wait before opening again a subscription the server ended: it doubles
 * each time the server ends it again soon after, up to REOPEN_MAX_MS.
 */
export const REOPEN_MIN_MS = 1_000
export const REOPEN_MAX_MS = 30_000
/** Open this long, the next end counts as a first one again. */
const STEADY_MS = 60_000
/**
 * How long after a reopen, or the socket's return, the gap is announced:
 * the server has the subscriptions by then, so nothing published after the
 * caches are read again is lost. The announcements within it are one.
 */
export const SETTLE_MS = 500

// Stable per-document id for registry keys. Document objects are module-level
// constants generated by gql codegen, so WeakMap identity is reliable.
let nextDocId = 0
const docIdCache = new WeakMap<AnyDocument, number>()
const opNameCache = new WeakMap<AnyDocument, string | undefined>()

function docId(doc: AnyDocument): number {
  let id = docIdCache.get(doc)
  if (id === undefined) {
    id = ++nextDocId
    docIdCache.set(doc, id)
  }
  return id
}

// The name on the document's operation definition, e.g. `subscription Foo {` →
// "Foo". Anonymous operations have none, which is why the result is optional:
// graphql-ws omits operationName rather than sending null.
//
// Codegen emits one operation per document and always puts its definition first
// — any fragments it uses are appended after it — so the first match is the
// operation. Matching is anchored to the start of a line because a field named
// e.g. `subscriptionStatus` deeper in the selection set would otherwise match.
const OPERATION_NAME_RE = /^\s*(?:query|mutation|subscription)\s+(\w+)/m

function opNameFor(doc: AnyDocument): string | undefined {
  if (opNameCache.has(doc)) return opNameCache.get(doc)
  const name = doc.toString().match(OPERATION_NAME_RE)?.[1]
  opNameCache.set(doc, name)
  return name
}

// eslint-disable-next-line @typescript-eslint/no-explicit-any
const registry = new Map<string, SharedSubscription<any>>()

// --- Gaps ---
//
// Events published while a subscription is not open are gone: the event bus
// has no replay, so a document created by a colleague — or by an operator's
// own MCP agent, which is the case where the tab is hidden *by definition* —
// never reaches the caches that were relying on the subscription to
// invalidate them. A subscription is not open:
//
// - while the tab is hidden: they are torn down then (below);
// - while the socket is down: graphql-ws connects again and subscribes them
//   again on its own, and says nothing to them of what was published
//   meanwhile;
// - after the server ended one: it refused it (gqlgen answers a resolver's
//   error with a result holding errors and no data, then completes), or
//   core's bus dropped events for it because it fell behind, and it ended
//   rather than go on with holes. It is opened again after a wait.
//
// The registry knows exactly when each gap opened and closed, so it says so.
// Deciding what to refetch is not its business; that belongs to whoever owns
// the caches (see hooks/use-resume-refetch.ts).

const resumeListeners = new Set<() => void>()

// True once a hidden tab has torn subscriptions down (or the server ended
// one while hidden), until the resume has been announced. Guards against
// firing on a visibilitychange that disposed nothing — an alt-tab with no
// subscriptions mounted loses no events.
let gapOpen = false

// The tab is hidden: nothing opens again until it shows.
let paused = false

// A gap to announce once SETTLE_MS has passed (announceSoon).
let announcing: ReturnType<typeof setTimeout> | null = null

/**
 * Register a callback for "subscriptions were down and are now back". Returns
 * an unsubscribe function.
 */
export function onSubscriptionsResumed(callback: () => void): () => void {
  resumeListeners.add(callback)
  return () => {
    resumeListeners.delete(callback)
  }
}

function announceResume() {
  if (announcing !== null) {
    // This one covers it.
    clearTimeout(announcing)
    announcing = null
  }
  // Copy before iterating — a listener may unregister in response.
  for (const listener of Array.from(resumeListeners)) {
    listener()
  }
}

/** Announces a gap once SETTLE_MS has passed; those that come meanwhile are one. */
function announceSoon() {
  if (announcing !== null) return
  announcing = setTimeout(() => {
    announcing = null
    if (paused) {
      // Hidden meanwhile: the tab's return announces it.
      gapOpen = true
      return
    }
    announceResume()
  }, SETTLE_MS)
}

// The socket the subscriptions share. One that closes while any is open
// loses what is published until graphql-ws has it back: announced then.
let watched: Client | null = null
let socketGap = false

function client(): Client {
  const c = getGraphQLWSClient()
  if (watched !== c) {
    watched = c
    c.on("closed", () => {
      for (const sub of registry.values()) {
        if (sub.open) {
          socketGap = true
          return
        }
      }
    })
    c.on("connected", () => {
      if (!socketGap) return
      socketGap = false
      announceSoon()
    })
  }
  return c
}

function keyFor(document: AnyDocument, variables: unknown): string {
  return `${docId(document)}:${JSON.stringify(variables ?? null)}`
}

/**
 * Subscribe to a GraphQL subscription. Returns an unsubscribe function.
 * Multiple callers with the same (document, variables) share one underlying
 * graphql-ws subscription.
 */
export function subscribe<TResult, TVariables>(
  document: TypedDocumentString<TResult, TVariables>,
  variables: TVariables | undefined,
  listener: Listener<TResult>,
  onError?: ErrorListener,
): () => void {
  const doc = document as unknown as AnyDocument
  const key = keyFor(doc, variables)
  let sub = registry.get(key) as SharedSubscription<TResult> | undefined

  if (!sub) {
    sub = {
      key,
      query: doc.toString(),
      operationName: opNameFor(doc),
      variables,
      listeners: new Set(),
      errorListeners: new Set(),
      dispose: null,
      open: null,
      openedAt: 0,
      ends: 0,
      retry: null,
    }
    registry.set(key, sub)
  }

  sub.listeners.add(listener)
  if (onError) sub.errorListeners.add(onError)

  // First listener on a fresh entry — open the underlying graphql-ws sub.
  if (sub.listeners.size === 1 && !sub.open && sub.retry === null) {
    openSubscription(sub)
  }

  return () => {
    if (!sub) return
    sub.listeners.delete(listener)
    if (onError) sub.errorListeners.delete(onError)
    if (sub.listeners.size === 0) {
      teardown(sub)
    }
  }
}

function openSubscription<T>(sub: SharedSubscription<T>) {
  const token = {}
  sub.open = token
  sub.openedAt = Date.now()
  sub.dispose = client().subscribe<T>(
    {
      query: sub.query,
      variables: sub.variables as Record<string, unknown> | undefined,
      operationName: sub.operationName,
    },
    {
      next: (msg) => {
        if (sub.open !== token) return
        if (!msg.data) {
          // How gqlgen refuses a subscription (its resolver's error): a
          // result with errors and no data, then complete.
          if (msg.errors?.length) refused(sub, msg.errors)
          return
        }
        // Copy listeners to an array before iterating — a listener may
        // unsubscribe (mutating the Set) in response to the event.
        for (const listener of Array.from(sub.listeners)) {
          listener(msg.data as T)
        }
      },
      error: (err) => {
        if (sub.open !== token) return
        // A GraphQL error message ends the subscription, as a close the
        // client does not retry does (a fatal code). Transport errors it
        // retries are the client's, and never reach here.
        if (Array.isArray(err)) refused(sub, err)
        ended(sub)
      },
      complete: () => {
        if (sub.open !== token) return
        ended(sub)
      },
    },
  )
}

/**
 * A refusal, logged so it does not fail silently (an auth misconfiguration
 * on a subscription used to be impossible to spot from the client), and
 * told to its error listeners.
 */
function refused<T>(sub: SharedSubscription<T>, errors: readonly unknown[]) {
  const messages = errors
    .map((e) => (e as { message?: string })?.message)
    .filter(Boolean)
    .join("; ")
  console.error(`[graphql-ws] subscription "${sub.operationName ?? "(anonymous)"}" rejected: ${messages}`)
  for (const l of Array.from(sub.errorListeners)) {
    l(messages)
  }
}

/**
 * The server ended the subscription: open it again after a wait, longer each
 * time the server ends it again soon after, and announce the gap once it is
 * back.
 */
function ended<T>(sub: SharedSubscription<T>) {
  sub.open = null
  sub.dispose = null
  if (sub.listeners.size === 0) return
  if (paused) {
    // The tab's return opens it, and announces the gap.
    gapOpen = true
    return
  }
  if (Date.now() - sub.openedAt >= STEADY_MS) sub.ends = 0
  const wait = Math.min(REOPEN_MIN_MS * 2 ** sub.ends, REOPEN_MAX_MS)
  sub.ends++
  sub.retry = setTimeout(() => {
    sub.retry = null
    if (sub.listeners.size === 0 || paused || sub.open) return
    openSubscription(sub)
    announceSoon()
  }, wait)
}

/** Closes it from here: its late callbacks are ignored, and a reopen waiting is called off. */
function close<T>(sub: SharedSubscription<T>) {
  sub.open = null
  if (sub.retry !== null) {
    clearTimeout(sub.retry)
    sub.retry = null
  }
  if (sub.dispose) {
    try {
      sub.dispose()
    } catch {
      // ignore — client may already be disposed
    }
    sub.dispose = null
  }
}

function teardown<T>(sub: SharedSubscription<T>) {
  close(sub)
  // An unsubscribe called twice must not take a newer entry for the key.
  if (registry.get(sub.key) === sub) registry.delete(sub.key)
}

// --- Tab visibility: pause subscriptions while hidden, resume on visible ---
// Background tabs holding open WebSockets waste server resources and are
// routinely throttled or killed by browsers anyway. Dispose every active
// subscription on hidden — graphql-ws closes the underlying socket once
// refcount reaches zero (lazy: true). On visible, re-open every subscription
// that still has listeners; getGraphQLWSClient() lazily rebuilds the socket
// on the first reopen.
//
// The two halves are exported so the gap bookkeeping can be tested without a
// DOM environment; the listener below is the only production caller.

/** Tear down every open subscription. Anything published from here until
 *  resumeSubscriptions() is lost — there is no replay. */
export function pauseSubscriptions() {
  paused = true
  for (const sub of registry.values()) {
    if (sub.open || sub.retry !== null) {
      close(sub)
      gapOpen = true
    }
  }
}

/** Re-open every subscription that still has listeners, then announce the gap
 *  to anyone who needs to catch their caches up. */
export function resumeSubscriptions() {
  paused = false
  for (const sub of registry.values()) {
    if (!sub.open && sub.listeners.size > 0) {
      close(sub)
      sub.ends = 0
      openSubscription(sub)
    }
  }
  if (gapOpen) {
    gapOpen = false
    announceResume()
  }
}

if (typeof document !== "undefined") {
  document.addEventListener("visibilitychange", () => {
    if (document.visibilityState === "hidden") {
      pauseSubscriptions()
    } else {
      resumeSubscriptions()
    }
  })
}
