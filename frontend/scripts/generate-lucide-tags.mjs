#!/usr/bin/env node
// Regenerates src/components/wiki/lucide-tags.generated.ts.
//
// lucide publishes a keyword per icon — `password` on `key`, `shell` on `egg`,
// `command line` on `terminal` — and it is what the search on lucide.dev
// matches against. It does not ship in `lucide-react`, which is compiled
// components and nothing else, so a picker built on that package can only see
// the words inside the names. This script brings the metadata in.
//
// It reads the INSTALLED lucide-react version and fetches `lucide-static` at
// exactly that version, because the two are released in lockstep and a
// mismatched pair silently tags icons we do not have while leaving ours bare.
//
// Fetching rather than depending: `lucide-static` is ~50 MB unpacked, all of
// it SVGs and fonts we already have in another form, and a devDependency is
// paid for on every CI install. The generated file is committed instead, so
// nothing but this script — run by hand, after a lucide bump — needs network.
//
//   npm run gen:icon-tags
//
// icon-search-tags.test.ts fails if the committed file drifts from the
// installed icon set, which is what catches a bump nobody regenerated.

import { readFileSync, readdirSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const ICONS_DIR = join(root, "node_modules/lucide-react/dist/esm/icons")
const OUT = join(root, "src/components/wiki/lucide-tags.generated.ts")

function kebabToPascal(s) {
  return s
    .split("-")
    .map((p) => (p.length === 0 ? "" : p[0].toUpperCase() + p.slice(1)))
    .join("")
}

/** Lowercase words of a name or a tag — "command line" → ["command", "line"]. */
function words(s) {
  return s.toLowerCase().match(/[a-z]+|[0-9]+/g) ?? []
}

const version = JSON.parse(
  readFileSync(join(root, "node_modules/lucide-react/package.json"), "utf8"),
).version

// The installed set, by lucide's own kebab key. Mirrors the import.meta.glob
// in icon-catalog.ts, including the `index` barrel it has to skip.
const installed = new Map()
for (const file of readdirSync(ICONS_DIR)) {
  const match = /^(.+)\.m?js$/.exec(file)
  if (!match || file.endsWith(".map")) continue
  const kebab = match[1]
  if (kebab === "index") continue
  installed.set(kebab, kebabToPascal(kebab))
}

const url = `https://cdn.jsdelivr.net/npm/lucide-static@${version}/tags.json`
process.stdout.write(`lucide-react ${version} — ${installed.size} icons installed\nfetching ${url}\n`)

const response = await fetch(url)
if (!response.ok) {
  process.stderr.write(
    `\nFailed: ${response.status} ${response.statusText}\n` +
      `No lucide-static at ${version}? Check the published versions before\n` +
      `pinning this to a different one — the two packages track each other.\n`,
  )
  process.exit(1)
}
const upstream = await response.json()

const tags = {}
let kept = 0
let dropped = 0
let unknown = 0

for (const [kebab, list] of Object.entries(upstream).sort(([a], [b]) =>
  a.localeCompare(b),
)) {
  const name = installed.get(kebab)
  if (!name) {
    unknown++
    continue
  }
  const own = new Set(words(kebab))
  const seen = new Set()
  const useful = []
  for (const raw of list) {
    const tag = raw.toLowerCase().trim()
    if (!tag || seen.has(tag)) continue
    seen.add(tag)
    // A tag saying what the name already says costs bytes and buys no recall:
    // "terminal" on `square-terminal` is already a token of the name, and the
    // token tier outranks the tag tier anyway.
    if (words(tag).every((w) => own.has(w))) {
      dropped++
      continue
    }
    useful.push(tag)
    kept++
  }
  if (useful.length > 0) tags[name] = useful
}

const body = Object.entries(tags)
  .map(([name, list]) => `  ${name}: ${JSON.stringify(list)},`)
  .join("\n")

const file = `// GENERATED by scripts/generate-lucide-tags.mjs — do not edit.
//
// Source: lucide-static@${version}/tags.json (ISC), the same metadata the
// search on lucide.dev matches against, keyed by the PascalCase name this app
// stores instead of lucide's kebab-case. Tags that only repeat words already
// in the icon's own name are dropped; see the script for why.
//
// Regenerate with \`npm run gen:icon-tags\` after bumping lucide-react.

const LUCIDE_TAGS: Readonly<Record<string, readonly string[]>> = {
${body}
}

export default LUCIDE_TAGS
`

writeFileSync(OUT, file)

const coverage = ((Object.keys(tags).length / installed.size) * 100).toFixed(1)
process.stdout.write(
  `wrote ${OUT.slice(root.length + 1)}\n` +
    `  ${Object.keys(tags).length} icons tagged (${coverage}% of installed)\n` +
    `  ${kept} tags kept, ${dropped} dropped as already in the name\n` +
    `  ${unknown} upstream keys skipped — not in the installed set\n`,
)
